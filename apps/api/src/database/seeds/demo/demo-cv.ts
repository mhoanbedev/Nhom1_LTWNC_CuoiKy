/**
 * PDF CV mẫu cho seed demo, dựng bằng code (không cần file nhị phân trong repo). Chữ chỉ dùng ASCII
 * vì font Helvetica chuẩn của PDF không có dấu tiếng Việt.
 */

/** PDF một trang, mỗi phần tử của `lines` là một dòng chữ. */
export function buildPdf(lines: readonly string[]): Buffer {
  const escape = (text: string) => text.replace(/[\\()]/g, (char) => `\\${char}`);
  const content = [
    'BT',
    '/F1 12 Tf',
    '14 TL',
    '50 780 Td',
    ...lines.map((line) => `(${escape(line)}) '`),
    'ET',
  ].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];

  let body = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(body));
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefAt = Buffer.byteLength(body);
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  body += offsets.map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`).join('');
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefAt}\n%%EOF\n`;
  return Buffer.from(body, 'latin1');
}

export interface SeedCv {
  /** public_id cố định trên Cloudinary (folder `seed/`): chạy lại seed không sinh file rác. */
  fileName: string;
  originalName: string;
  buffer: Buffer;
}

/** 3 CV mẫu dùng chung cho mọi ứng viên demo. */
export function seedCvs(): SeedCv[] {
  const cv = (fileName: string, originalName: string, title: string, skills: string) => ({
    fileName,
    originalName,
    buffer: buildPdf([
      'CURRICULUM VITAE (DEMO)',
      '',
      `Position: ${title}`,
      `Skills: ${skills}`,
      'Education: Bachelor of Information Technology (expected 2027)',
      '',
      'This is sample data generated by `make seed-demo`.',
    ]),
  });
  return [
    cv('cv-backend.pdf', 'CV-Backend.pdf', 'Backend Intern', 'Node.js, NestJS, PostgreSQL, Docker'),
    cv('cv-frontend.pdf', 'CV-Frontend.pdf', 'Frontend Intern', 'React, Next.js, TypeScript, CSS'),
    cv('cv-data.pdf', 'CV-Data.pdf', 'Data Analyst Intern', 'SQL, Python, Excel, Power BI'),
  ];
}
